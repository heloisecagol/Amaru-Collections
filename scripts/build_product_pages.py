def read_products():
    """Pull name and price for each id out of products.js."""
    src = (SITE / "js" / "products.js").read_text()
    out = {}
    for block in re.findall(r"\{[^{}]*?id: \"([^\"]+)\"(.*?)\n  \}", src, re.S):
        pid, body = block
        name = re.search(r'name: \{ en: "([^"]+)" \}', body).group(1)
        price = int(re.search(r"price: (\d+)", body).group(1))
        out[pid] = {"name": name, "price": price}
    return out


