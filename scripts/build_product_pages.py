def main():
    products = read_products()
    out_dir = SITE / "shop"
    out_dir.mkdir(exist_ok=True)
    for pid, extra in EARRINGS.items():
        p = products[pid]
        page = TEMPLATE.format(
            id=pid,
            name=html.escape(p["name"]),
            price=p["price"],
            price_fmt=f"€{p['price']}",
            alt=html.escape(extra["alt"]),
            domain=DOMAIN,
        )
        (out_dir / f"{pid}.html").write_text(page)
        print(f"wrote site/shop/{pid}.html  ({p['name']}, €{p['price']})")


if __name__ == "__main__":
    main()
